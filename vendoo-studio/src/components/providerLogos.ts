export function hasProviderLogo(id: string): id is ProviderLogoId {
  return id === "chatgpt" || id === "mimo" || id === "cursor";
}

/** Map API provider names (and settings ids) to a logo id. */
export function resolveProviderLogoId(provider: string | undefined | null): ProviderLogoId | null {
  if (provider === "chatgpt") return "chatgpt";
  if (provider === "mimo" || provider === "xiaomi-mimo") return "mimo";
  if (provider === "cursor") return "cursor";
  return null;
}
